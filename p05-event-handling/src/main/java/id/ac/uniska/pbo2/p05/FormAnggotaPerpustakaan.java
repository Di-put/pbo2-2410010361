    private void daftarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_daftarButtonActionPerformed
        // TODO add your handling code here:
        String npm = npmField.getText().trim();
        String nama = namaField.getText().trim();
        
        
        String programStudi = prodiCombo.getSelectedItem().toString();
       
        String jenisAnggota = "";
            if (mahasiswaRadio.isSelected()) {        
                jenisAnggota = "Mahasiswa";
        } else if (dosenRadio.isSelected()) { 
                jenisAnggota = "Dosen";
        } else if (umumRadio.isSelected()) { 
                jenisAnggota = "Umum";
    }

        String pesan = "Data Pendaftaran Anggota:\n" +
                   "NPM: " + npm + "\n" +
                   "Nama: " + nama + "\n" +
                   "Program Studi: " + programStudi + "\n" +
                   "Jenis Anggota : " + jenisAnggota;
                

        javax.swing.JOptionPane.showMessageDialog(this, pesan, "Konfirmasi Pendaftaran", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_daftarButtonActionPerformed

